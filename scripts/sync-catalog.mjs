#!/usr/bin/env node
/**
 * Generate skills/attention-engineering/references/catalog.md from README.md.
 *
 * Usage:
 *   node scripts/sync-catalog.mjs          # write the catalog
 *   node scripts/sync-catalog.mjs --check  # verify the catalog is up to date
 *
 * Only bullet entries of the form "- [Name](url) - Description." inside
 * "## " sections that follow "## Contents" are collected. Sections that are
 * not resource categories are skipped.
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const README_PATH = resolve(ROOT, 'README.md');
const CATALOG_PATH = resolve(ROOT, 'skills/attention-engineering/references/catalog.md');

const CHECK = process.argv.includes('--check');

const CONTENTS_HEADING = 'contents';
const SKIPPED_SECTIONS = new Set([
  'contents',
  'the five principles',
  'anti-patterns',
  'contributing',
  'license',
]);

const H2_RE = /^##[ \t]+(.+?)[ \t]*#*[ \t]*$/;
const ENTRY_RE = /^[ \t]*[-*][ \t]+\[([^\]]+)\]\(([^()\s]+)\)[ \t]+[-–—][ \t]+(.+?)[ \t]*$/;
const FENCE_RE = /^[ \t]*(```|~~~)/;

function fail(message) {
  console.error(`sync-catalog: ${message}`);
  process.exit(1);
}

function readReadme() {
  if (!existsSync(README_PATH)) {
    fail(`README.md not found at ${README_PATH}`);
  }
  return readFileSync(README_PATH, 'utf8');
}

function parseCategories(markdown) {
  const lines = markdown.split(/\r?\n/);
  const categories = [];
  let inFence = false;
  let seenContents = false;
  let current = null;

  for (const line of lines) {
    if (FENCE_RE.test(line)) {
      inFence = !inFence;
      continue;
    }
    if (inFence) {
      continue;
    }

    const heading = H2_RE.exec(line);
    if (heading) {
      const title = heading[1].trim();
      const key = title.toLowerCase();

      if (!seenContents) {
        if (key === CONTENTS_HEADING) {
          seenContents = true;
        }
        current = null;
        continue;
      }

      if (SKIPPED_SECTIONS.has(key)) {
        current = null;
        continue;
      }

      current = { title, entries: [] };
      categories.push(current);
      continue;
    }

    if (!current) {
      continue;
    }

    const entry = ENTRY_RE.exec(line);
    if (!entry) {
      continue;
    }

    current.entries.push({
      name: entry[1].trim(),
      url: entry[2].trim(),
      description: entry[3].replace(/\s+/g, ' ').trim(),
    });
  }

  if (!seenContents) {
    fail('README.md has no "## Contents" section.');
  }

  return categories;
}

function render(categories) {
  const out = [
    '# Catalog',
    '',
    '<!-- Generated by scripts/sync-catalog.mjs. Do not edit by hand. -->',
    '',
  ];

  for (const category of categories) {
    out.push(`## ${category.title}`, '');
    for (const entry of category.entries) {
      out.push(`- [${entry.name}](${entry.url}) - ${entry.description}`);
    }
    out.push('');
  }

  return `${out.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`;
}

function summarizeDiff(expected, actual) {
  const expectedLines = expected.split('\n');
  const actualLines = actual.split('\n');
  const length = Math.max(expectedLines.length, actualLines.length);

  let firstDifference = -1;
  let differingLines = 0;

  for (let i = 0; i < length; i += 1) {
    if (expectedLines[i] !== actualLines[i]) {
      if (firstDifference === -1) {
        firstDifference = i;
      }
      differingLines += 1;
    }
  }

  const summary = [`  differing lines: ${differingLines}`];

  if (firstDifference !== -1) {
    summary.push(`  first difference at line ${firstDifference + 1}:`);
    summary.push(`    expected: ${JSON.stringify(expectedLines[firstDifference] ?? '<missing>')}`);
    summary.push(`    actual:   ${JSON.stringify(actualLines[firstDifference] ?? '<missing>')}`);
  }

  return summary.join('\n');
}

function main() {
  const generated = render(parseCategories(readReadme()));

  if (CHECK) {
    if (!existsSync(CATALOG_PATH)) {
      console.error(`sync-catalog: missing ${relative(ROOT, CATALOG_PATH)}`);
      console.error('Run: node scripts/sync-catalog.mjs');
      process.exit(1);
    }

    const existing = readFileSync(CATALOG_PATH, 'utf8');
    if (existing === generated) {
      console.log('sync-catalog: catalog is up to date.');
      return;
    }

    console.error('sync-catalog: catalog is out of date.');
    console.error(summarizeDiff(generated, existing));
    console.error('Run: node scripts/sync-catalog.mjs');
    process.exit(1);
  }

  mkdirSync(dirname(CATALOG_PATH), { recursive: true });
  writeFileSync(CATALOG_PATH, generated, 'utf8');
  console.log(`sync-catalog: wrote ${relative(ROOT, CATALOG_PATH)}`);
}

main();
